def find_xpr(project: Path) -> Path:
    if project.is_file() and project.suffix.lower() == ".xpr":
        return project.resolve()
    matches = sorted(project.rglob("*.xpr"))
    if not matches:
        raise FileNotFoundError(f"No .xpr file found under {project}")
    if len(matches) > 1:
        preferred = [p for p in matches if ".runs" not in p.parts and ".cache" not in p.parts]
        matches = preferred or matches
    return matches[0].resolve()


def find_standard_impl_bit(project: Path) -> Path:
    xpr = find_xpr(project)
    impl_dir = xpr.parent / f"{xpr.stem}.runs" / "impl_1"
    bits = sorted(impl_dir.glob("*.bit"))
    if not bits:
        raise FileNotFoundError(f"No standard implementation bitstream found under {impl_dir}")
    return bits[0].resolve()


def parse_xpr_basic(xpr: Path) -> dict[str, str]:
    data = {
        "project_name": xpr.stem,
        "part": "xc7z020clg400-1",
        "board_part": "",
        "target_language": "Verilog",
        "simulator_language": "Mixed",
        "top": "",
    }
    try:
        root = ElementTree.parse(xpr).getroot()
    except ElementTree.ParseError:
        return data

    text = ElementTree.tostring(root, encoding="unicode")
    for key in ("Part", "PART", "part"):
        marker = f'Name="{key}" Val="'
        if marker in text:
            data["part"] = text.split(marker, 1)[1].split('"', 1)[0]
            break
    for key in ("BoardPart", "board_part"):
        marker = f'Name="{key}" Val="'
        if marker in text:
            data["board_part"] = text.split(marker, 1)[1].split('"', 1)[0]
            break
    for key, out_key in (
        ("TargetLanguage", "target_language"),
        ("SimulatorLanguage", "simulator_language"),
        ("TopModule", "top"),
    ):
        marker = f'Name="{key}" Val="'
        if marker in text:
            data[out_key] = text.split(marker, 1)[1].split('"', 1)[0]
    return data


def should_ignore(path: Path) -> bool:
    return any(part in IGNORE_DIRS for part in path.parts)


def collect_files(root: Path, exts: set[str]) -> list[Path]:
    files: list[Path] = []
    for path in root.rglob("*"):
        if should_ignore(path):
            continue
        if path.is_file() and path.suffix in exts:
            files.append(path.resolve())
    return sorted(files)


def collect_component_xml(root: Path) -> list[Path]:
    files: list[Path] = []
    for path in root.rglob("component.xml"):
        if should_ignore(path):
            continue
        if path.is_file():
            files.append(path.resolve())
    return sorted(files)


def manifest_from_project(project: Path) -> ProjectManifest:
    xpr = find_xpr(project)
    root = xpr.parent
    info = parse_xpr_basic(xpr)
    bd_files = collect_files(root, BD_EXTS)
    xci_files = collect_files(root, IP_EXTS)
    bd_tcl_files = [path for path in collect_files(root, BD_TCL_EXTS) if "bd" in path.stem.lower()]
    hdl_files = collect_files(root, HDL_EXTS)
    xdc_files = collect_files(root, XDC_EXTS)
    app_files = collect_files(root, APP_EXTS)
    return ProjectManifest(
        source_project=norm(xpr),
        project_name=info["project_name"],
        part=info["part"],
        board_part=info["board_part"],
        target_language=info["target_language"],
        simulator_language=info["simulator_language"],
        top=info["top"],
        hdl_files=[norm(p) for p in hdl_files],
        xdc_files=[norm(p) for p in xdc_files],
        app_files=[norm(p) for p in app_files],
        bd_files=[norm(p) for p in bd_files],
        xci_files=[norm(p) for p in xci_files],
        ip_component_files=[norm(p) for p in collect_component_xml(root)],
        bd_tcl_files=[norm(p) for p in bd_tcl_files],
    )


def tcl_list(paths: Iterable[str]) -> str:
    return " ".join("{" + p.replace("\\", "/") + "}" for p in paths)


def write_export_tcl(manifest: ProjectManifest, out_dir: Path) -> Path:
    script = out_dir / "01_export_bd_from_source_vivado.tcl"
    bd_out = (out_dir / "bd_tcl").resolve().as_posix()
    ensure_dir(out_dir / "bd_tcl")
    script.write_text(
        f"""# Auto-generated. Run with the source Vivado version, for example 2020.2.
set source_xpr {{{manifest.source_project}}}
set bd_export_dir {{{bd_out}}}
file mkdir $bd_export_dir

open_project $source_xpr
set exported 0
foreach bd [get_files -quiet -filter {{FILE_TYPE == "Block Designs"}}] {{
    set bd_name [file rootname [file tail $bd]]
    open_bd_design $bd
    validate_bd_design
    write_bd_tcl -force [file join $bd_export_dir "${{bd_name}}.tcl"]
    close_bd_design [get_bd_designs $bd_name]
    incr exported
}}
report_ip_status -name ip_status -file [file join $bd_export_dir ip_status_source.rpt]
close_project
puts "Exported $exported block design Tcl file(s) to $bd_export_dir"
""",
        encoding="utf-8",
    )
    return script


def write_rebuild_tcl(manifest: ProjectManifest, out_dir: Path, new_project_dir: Path) -> Path:
    script = out_dir / "02_rebuild_project_in_target_vivado.tcl"
    project_dir = new_project_dir.resolve().as_posix()
    bd_dir = (out_dir / "bd_tcl").resolve().as_posix()
    hdl = tcl_list(manifest.hdl_files)
    xdc = tcl_list(manifest.xdc_files)
    xci = tcl_list(manifest.xci_files)
    top_line = f"set_property top {{{manifest.top}}} [current_fileset]" if manifest.top else "# Top is inferred after compile-order update."
    board_part_line = (
        f"set_property board_part {{{manifest.board_part}}} [current_project]"
        if manifest.board_part
        else "# Source project had no BoardPart property."
    )
    script.write_text(
        f"""# Auto-generated. Run with the target Vivado version, for example 2021.1.
set project_name {{{manifest.project_name}_migrated}}
set project_dir {{{project_dir}}}
set part {{{manifest.part}}}
set bd_export_dir {{{bd_dir}}}

file mkdir $project_dir
create_project $project_name $project_dir -part $part -force
{board_part_line}
set_property target_language {{{manifest.target_language}}} [current_project]
set_property simulator_language {{{manifest.simulator_language}}} [current_project]
set_property TARGET_SIMULATOR XSim [current_project]

set hdl_files [list {hdl}]
if {{[llength $hdl_files] > 0}} {{
    add_files -fileset sources_1 $hdl_files
}}

set xdc_files [list {xdc}]
if {{[llength $xdc_files] > 0}} {{
    add_files -fileset constrs_1 $xdc_files
}}

set xci_files [list {xci}]
if {{[llength $xci_files] > 0}} {{
    add_files -norecurse $xci_files
}}

foreach bd_tcl [glob -nocomplain [file join $bd_export_dir *.tcl]] {{
    if {{[file tail $bd_tcl] eq "ip_status_source.rpt"}} {{
        continue
    }}
    puts "Recreating block design from $bd_tcl"
    source $bd_tcl
    validate_bd_design
    save_bd_design
}}

foreach bd [get_files -quiet -filter {{FILE_TYPE == "Block Designs"}}] {{
    set wrapper [make_wrapper -files $bd -top]
    add_files -norecurse $wrapper
}}

if {{[llength [get_ips -quiet]] > 0}} {{
    report_ip_status -name ip_status_before_upgrade -file [file join $project_dir ip_status_before_upgrade.rpt]
    upgrade_ip -quiet [get_ips]
    generate_target all [get_ips]
    report_ip_status -name ip_status_after_upgrade -file [file join $project_dir ip_status_after_upgrade.rpt]
}}

update_compile_order -fileset sources_1
{top_line}
# Project changes are written by create_project/add_files in batch mode.
puts "Migrated project created at $project_dir/$project_name.xpr"
close_project
""",
        encoding="utf-8",
    )
    return script


def write_text(path: Path, content: str) -> Path:
    ensure_dir(path.parent)
    path.write_text(content, encoding="utf-8", newline="\n")
    return path


HOOK_STAGES = {
    "pre_build",
    "post_build",
    "pre_synth",
    "post_synth",
    "pre_impl",
    "post_impl",
    "pre_bitstream",
    "post_bitstream",
    "pre_hw_export",
    "post_hw_export",
}


def load_hook_config(args: argparse.Namespace, root: Path) -> dict[str, list[dict[str, str]]]:
    hooks: dict[str, list[dict[str, str]]] = {stage: [] for stage in HOOK_STAGES}
    config_path = getattr(args, "hooks_config", "") or ""
    if config_path:
        data = json.loads(Path(config_path).resolve().read_text(encoding="utf-8-sig"))
        raw_hooks = data.get("hooks", data)
        for stage, entries in raw_hooks.items():
            if stage not in HOOK_STAGES:
                raise ValueError(f"Unsupported hook stage: {stage}")
            if isinstance(entries, (str, dict)):
                entries = [entries]
            for entry in entries:
                if isinstance(entry, str):
                    entry = {"type": "tcl", "path": entry}
                hooks[stage].append({"type": entry.get("type", "tcl"), "path": str(entry["path"])})
    for raw in getattr(args, "hook", []) or []:
        if ":" not in raw:
            raise ValueError(f"Hook must use stage:path syntax: {raw}")
        stage, path = raw.split(":", 1)
        if stage not in HOOK_STAGES:
            raise ValueError(f"Unsupported hook stage: {stage}")
        hooks[stage].append({"type": "tcl", "path": path})
    for stage, entries in hooks.items():
        for entry in entries:
            if entry["type"] != "tcl":
                raise ValueError(f"Only Tcl hooks are supported inside Vivado workflows: {stage} {entry}")
            hook_path = workflow_path(root, entry["path"])
            if not hook_path.exists():
                raise FileNotFoundError(f"Hook file does not exist for {stage}: {hook_path}")
            entry["path"] = hook_path.as_posix()
    return hooks


def hook_tcl_block(hooks: dict[str, list[dict[str, str]]], stage: str) -> str:
    entries = hooks.get(stage, [])
    if not entries:
        return f'puts "No hooks for {stage}."'
    lines = [f'puts "Running {stage} hook: {entry["path"]}"\nsource {{{entry["path"]}}}' for entry in entries]
    return "\n".join(lines)


def workflow_glob_tcl(directory: str, patterns: list[str], fileset: str, recurse: bool = False) -> str:
    flag = "-types f " if recurse else ""
    lines = []
    for pattern in patterns:
        glob_pattern = f"{directory}/**/{pattern}" if recurse else f"{directory}/{pattern}"
        lines.append(
            f"""set files [glob -nocomplain {flag}{{{glob_pattern}}}]
if {{[llength $files] > 0}} {{ add_files -fileset {fileset} $files }}"""
        )
    return "\n".join(lines)


