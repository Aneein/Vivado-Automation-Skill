def inspect_xsa(xsa: Path) -> dict:
    if not xsa.exists():
        raise RuntimeError(f"Expected XSA was not created: {xsa}")
    try:
        with zipfile.ZipFile(xsa) as archive:
            names = archive.namelist()
    except zipfile.BadZipFile as exc:
        raise RuntimeError(f"XSA is not a readable zip archive: {xsa}") from exc
    bit_files = [name for name in names if name.lower().endswith(".bit")]
    hwh_files = [name for name in names if name.lower().endswith(".hwh")]
    ps7_init_files = [name for name in names if name.lower().endswith("ps7_init.tcl")]
    ddr_ranges = extract_xsa_ddr_ranges(xsa, hwh_files)
    xsa_info = {
        "xsa": str(xsa),
        "entry_count": len(names),
        "bit_files": bit_files,
        "hwh_files": hwh_files,
        "ps7_init_files": ps7_init_files,
        "ddr_mem_ranges": ddr_ranges,
    }
    if not bit_files:
        raise RuntimeError(f"XSA does not contain a bitstream. Re-export with write_hw_platform -include_bit: {xsa}")
    if not hwh_files:
        raise RuntimeError(f"XSA does not contain an HWH hardware handoff file: {xsa}")
    return xsa_info


def _int_to_hex(value: int) -> str:
    return f"0x{value:08x}"


def parse_mem_range(value: str) -> tuple[str, str]:
    parts = re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", value)
    if len(parts) < 2:
        raise ValueError(f"Expected two addresses in memory range: {value}")
    low = int(parts[0], 0)
    high = int(parts[1], 0)
    if low > high:
        raise ValueError(f"Memory range low address is above high address: {value}")
    return _int_to_hex(low), _int_to_hex(high)


def ranges_overlap(left: tuple[str, str], right: tuple[str, str]) -> bool:
    left_low, left_high = (int(left[0], 0), int(left[1], 0))
    right_low, right_high = (int(right[0], 0), int(right[1], 0))
    return left_low <= right_high and right_low <= left_high


def extract_xsa_member(xsa: Path, member: str, out_dir: Path) -> Path:
    ensure_dir(out_dir)
    target = out_dir / Path(member).name
    with zipfile.ZipFile(xsa) as archive:
        data = archive.read(member)
    target.write_bytes(data)
    return target


def extract_xsa_ddr_ranges(xsa: Path, hwh_files: list[str] | None = None) -> list[dict[str, str]]:
    ranges: list[dict[str, str]] = []
    try:
        with zipfile.ZipFile(xsa) as archive:
            members = hwh_files or [name for name in archive.namelist() if name.lower().endswith(".hwh")]
            for member in members:
                try:
                    root = ElementTree.fromstring(archive.read(member))
                except (ElementTree.ParseError, KeyError):
                    continue
                for element in root.iter():
                    attrs = {key.upper(): value for key, value in element.attrib.items()}
                    base = attrs.get("BASEVALUE") or attrs.get("BASEADDR") or attrs.get("BASE")
                    high = attrs.get("HIGHVALUE") or attrs.get("HIGHADDR") or attrs.get("HIGH")
                    name = " ".join(
                        str(element.attrib.get(key, ""))
                        for key in ("INSTANCE", "NAME", "MEMTYPE", "SLAVEBUSINTERFACE", "FULLNAME")
                    )
                    if not base or not high or "DDR" not in name.upper():
                        continue
                    try:
                        low, high_addr = parse_mem_range(f"{base} {high}")
                    except ValueError:
                        continue
                    ranges.append({"source": member, "name": name.strip(), "low": low, "high": high_addr})
    except (OSError, zipfile.BadZipFile):
        return ranges
    return ranges


def find_vitis_loadhw_mem_ranges(log: Path) -> list[tuple[str, str]]:
    if not log.exists():
        raise RuntimeError(f"Vitis log does not exist: {log}")
    content = log.read_text(encoding="utf-8", errors="replace")
    ranges: list[tuple[str, str]] = []
    pattern = re.compile(r"loadhw\b[^\n\r]*?-mem-ranges\s+\[list\s+\{([^}]+)\}\]", re.IGNORECASE)
    for match in pattern.finditer(content):
        try:
            ranges.append(parse_mem_range(match.group(1)))
        except ValueError:
            continue
    return ranges


def diagnose_vitis_launch(args: argparse.Namespace) -> int:
    xsa = Path(args.xsa).resolve()
    info = inspect_xsa(xsa)
    xsa_ranges = [(entry["low"], entry["high"]) for entry in info["ddr_mem_ranges"]]
    if not xsa_ranges:
        xsa_ranges = [parse_mem_range(args.fallback_mem_range)]
    log_ranges = find_vitis_loadhw_mem_ranges(Path(args.ide_log).resolve())
    report = {
        "xsa": str(xsa),
        "ide_log": str(Path(args.ide_log).resolve()),
        "xsa_ddr_mem_ranges": [{"low": low, "high": high} for low, high in xsa_ranges],
        "vitis_loadhw_mem_ranges": [{"low": low, "high": high} for low, high in log_ranges],
        "mismatches": [],
    }
    for log_range in log_ranges:
        if not any(ranges_overlap(log_range, xsa_range) for xsa_range in xsa_ranges):
            report["mismatches"].append({"low": log_range[0], "high": log_range[1]})
    if args.out:
        out = Path(args.out).resolve()
        ensure_dir(out.parent)
        write_text(out, json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
    if report["mismatches"]:
        raise SystemExit("Vitis loadhw -mem-ranges does not overlap the XSA DDR range; generate a manual XSDB launch script.")
    return 0


def generate_xsdb_launch(args: argparse.Namespace) -> int:
    xsa = Path(args.xsa).resolve()
    elf = Path(args.elf).resolve()
